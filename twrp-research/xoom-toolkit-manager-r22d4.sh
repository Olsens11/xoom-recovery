#!/sbin/sh
# XoomToolkit R22d4: recovery-owned, allowlisted *manual* package lifecycle.
# Never reads SD-supplied scripts or modifies Android persistent partitions.
BB=/sbin/busybox
LOADER=/sbin/xoom-toolkit-verified-install
STATUS=/tmp/xoom-toolkit/status
CACHE=/tmp/xoom-toolkit/cache
RUNTIME=/tmp/XoomToolkit/toolkit/network-diagnostics/diag.sh
LOG=/tmp/xoom-toolkit/manual
bb() { "$BB" "$@"; }
notify() { bb mkdir -p "$LOG"; bb printf '%s\n' "$2" > "$LOG/$1.status"; bb echo "$1 $2"; }
approved() {
 case "$1" in
  wifi-runtime|network-diagnostics) return 0 ;;
  *) notify "$1" NOT_AVAILABLE;return 1;;
 esac
}
mounted_android_system() {
 bb grep -q ' /system ' /proc/mounts
}
installed_wifi() { [ -x /system/bin/wpa_supplicant ] && [ -x /system/bin/xoom_wpa_probe ]; }
installed_diag() { [ -f "$RUNTIME" ]; }
wifi_running() {
 [ "$(/sbin/getprop xoom.toolkit.wifi.runtime)" = READY ] ||
 bb pidof wpa_supplicant >/dev/null 2>&1 ||
 bb pidof dhcpcd >/dev/null 2>&1 ||
 bb pidof xoom_dns_proxy >/dev/null 2>&1
}
diag_running() { [ -e /tmp/xoom-toolkit/manual/diag.running ]; }
wifi_dependents() { installed_diag; }
get_state() {
 case "$1" in
  wifi-runtime)
   if wifi_running; then bb echo RUNNING
   elif installed_wifi; then bb echo LOADED
   else bb echo UNLOADED; fi ;;
  network-diagnostics)
   if diag_running; then bb echo RUNNING
   elif installed_diag; then bb echo LOADED
   else bb echo UNLOADED; fi ;;
  *) bb echo UNAVAILABLE ;;
 esac
}
run_load() {
 approved "$1" || return 2
 if mounted_android_system; then notify "$1" ANDROID_SYSTEM_MOUNTED;return 10;fi
 case "$1" in
  wifi-runtime)
   if installed_wifi; then notify "$1" ALREADY_LOADED;return 0;fi ;;
  network-diagnostics)
   if ! installed_wifi; then notify "$1" WIFI_DEPENDENCY_REQUIRED;return 11;fi
   if installed_diag; then notify "$1" ALREADY_LOADED;return 0;fi ;;
 esac
 "$LOADER" load "$1" || { notify "$1" LOAD_FAILED;return 12; }
 notify "$1" LOADED
}
run_start() {
 approved "$1" || return 2
 case "$1" in
  wifi-runtime)
   installed_wifi || { notify "$1" LOAD_FIRST;return 13; }
   if wifi_running; then notify "$1" ALREADY_RUNNING;return 0;fi
   /sbin/setprop xoom.toolkit.wifi.runtime READY
   if [ -s /external_sd/XoomToolkit/wifi.conf ]; then
    # The network controller runs as the existing init-managed service.
    /sbin/xoom-net-control start || { notify "$1" CONNECT_START_FAILED;return 14; }
   fi
   notify "$1" RUNNING
   ;;
  network-diagnostics)
   installed_diag || { notify "$1" LOAD_FIRST;return 13; }
   installed_wifi || { notify "$1" WIFI_DEPENDENCY_REQUIRED;return 11; }
   if diag_running; then notify "$1" ALREADY_RUNNING;return 0;fi
   bb mkdir -p /tmp/xoom-toolkit/manual
   bb touch /tmp/xoom-toolkit/manual/diag.running
   # Bounded one-shot diagnostic script; automatically returns to LOADED.
   /sbin/sh "$RUNTIME" > /tmp/xoom-toolkit/manual/diagnostics.log 2>&1
   outcome=$?
   bb rm -f /tmp/xoom-toolkit/manual/diag.running
   [ "$outcome" -eq 0 ] || { notify "$1" DIAGNOSTICS_FAILED;return 15; }
   notify "$1" DIAGNOSTICS_COMPLETE
   ;;
 esac
}
run_stop() {
 approved "$1" || return 2
 case "$1" in
  wifi-runtime)
   if ! wifi_running; then notify "$1" ALREADY_STOPPED;return 0;fi
   /sbin/xoom-net-control stop || { notify "$1" STOP_FAILED;return 16; }
   /sbin/setprop ctl.stop xoomdns || :
   /sbin/setprop xoom.toolkit.wifi.runtime STOPPED
   bb pidof wpa_supplicant >/dev/null 2>&1 &&
     { notify "$1" STILL_RUNNING;return 17; }
   notify "$1" STOPPED ;;
  network-diagnostics)
   if diag_running; then notify "$1" ONE_SHOT_BUSY;return 18;fi
   notify "$1" ALREADY_STOPPED ;;
 esac
}
# Unload list is generated by the *trusted recovery verifier*, not SD data.
# Every name must be an exact regular payload member under the proper root.
run_unload() {
 approved "$1" || return 2
 if mounted_android_system; then notify "$1" ANDROID_SYSTEM_MOUNTED;return 10;fi
 case "$1" in
  wifi-runtime)
   if wifi_running; then notify "$1" STOP_FIRST;return 20;fi
   if wifi_dependents; then notify "$1" DEPENDENT_LOADED;return 21;fi
   root=/ ;;
  network-diagnostics)
   if diag_running; then notify "$1" STOP_FIRST;return 20;fi
   root=/tmp/XoomToolkit/ ;;
 esac
 list="$CACHE/$1.files"
 if [ ! -r "$list" ]; then
  # A fresh recovery cannot have an installed module without a verifier cache.
  # Treat it as an error rather than trusting unvalidated filenames.
  if [ "$(get_state "$1")" = UNLOADED ]; then
   notify "$1" ALREADY_UNLOADED;return 0
  fi
  notify "$1" VERIFIED_FILELIST_MISSING;return 22
 fi
 count=0
 while IFS= read -r file; do
  count=$((count+1))
  [ "$count" -le 100 ] || { notify "$1" INVALID_FILELIST;return 23; }
  case "$1:$file" in
    wifi-runtime:system/*|network-diagnostics:toolkit/network-diagnostics/*) ;;
    *) notify "$1" UNSAFE_FILELIST;return 23 ;;
  esac
  case "$file" in
   /*|*../*|*/..|*./*|*/.|*\\*|*" "*|*:*) notify "$1" UNSAFE_FILELIST;return 23 ;;
  esac
 done < "$list"
 [ "$count" -gt 0 ] || { notify "$1" EMPTY_FILELIST;return 23; }
 # No partial deletion if *any* entry was invalid.
 while IFS= read -r file; do
  bb rm -f -- "$root$file" || { notify "$1" UNLOAD_FAILED;return 24; }
 done < "$list"
 case "$1" in
  wifi-runtime)
   /sbin/setprop xoom.toolkit.wifi.runtime STOPPED
   ;;
 esac
 bb printf '%s\n' UNLOADED > "$STATUS/$1"
 notify "$1" UNLOADED
}
[ "$#" -eq 2 ] || { bb echo 'usage: xoom-toolkit-manager load|start|stop|unload|status ID' >&2;exit 2; }
approved "$2" || exit 2
case "$1" in
 load) run_load "$2" ;;
 start) run_start "$2" ;;
 stop) run_stop "$2" ;;
 unload) run_unload "$2" ;;
 status) get_state "$2" ;;
 *) bb echo BAD_OPERATION >&2;exit 2 ;;
esac
